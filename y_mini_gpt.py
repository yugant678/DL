# STEP 4: CREATE INPUT AND TARGET SEQUENCES
# ------------------------------------------------------------

# GPT learns to predict the next token.
#
# Example:
# Input:  "python"
# Target: "ython "
#
# Every input position is trained to predict the next character.
#
# For an actual sequence:
# Input:  a r t i f i c i
